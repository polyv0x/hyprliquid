#!/usr/bin/env python3
"""Generate Rust data and CXX value conversions from the existing shared inputs.

No material constants or scalar descriptor tables are maintained in Rust by hand.
The C++ generator remains the source of the adapter's native aggregate layouts.
"""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
VARIANTS = json.loads((ROOT / 'materials/liquid.json').read_text())['variants']
PARAMS = re.findall(r'^GLASS_PARAM\((\w+), ([^,]+), ([^,]+), ([^)]+)\)',
                    (ROOT / 'src/MaterialParams.inc').read_text(), re.M)


def snake(name):
    return re.sub(r'(?<!^)([A-Z])', r'_\1', name).lower()


def scalar(value):
    return value.removesuffix('f') + '_f32'


def schema(value, name, definitions):
    if isinstance(value, dict):
        members = [(key, schema(item, name + key[0].upper() + key[1:], definitions))
                   for key, item in value.items()]
        definitions.append((name, members))
        return name
    if isinstance(value, list):
        kinds = [schema(item, name + 'Element', definitions) for item in value]
        assert kinds and len(set(kinds)) == 1, 'Material arrays must be homogeneous'
        return f'[{kinds[0]}; {len(kinds)}]'
    if value is None:
        return 'Option<f64>'
    if isinstance(value, bool):
        return 'bool'
    assert isinstance(value, (int, float))
    return 'f64'


def initializer(value, name):
    if isinstance(value, dict):
        return name + ' { ' + ', '.join(
            snake(key) + ': ' + initializer(item, name + key[0].upper() + key[1:])
            for key, item in value.items()) + ' }'
    if isinstance(value, list):
        return '[' + ', '.join(initializer(item, name + 'Element') for item in value) + ']'
    if value is None:
        return 'None'
    if isinstance(value, bool):
        return str(value).lower()
    return repr(float(value))


def definitions():
    default, dark = [], []
    schema(VARIANTS['default'], 'LiquidMaterial', default)
    schema(VARIANTS['dark'], 'LiquidMaterial', dark)
    assert default == dark, 'Material variants must use the same typed schema'
    return default


def structures(bridge=False):
    result = []
    for name, members in definitions():
        result.append('#[derive(Clone, Copy, Debug, Default, PartialEq)]\n'
                      f'pub struct {name} {{\n')
        for key, kind in members:
            if bridge:
                kind = kind.replace('Option<f64>', 'OptionalNumber')
            result.append(f'    pub {snake(key)}: {kind},\n')
        result.append('}\n')
    return ''.join(result)


def material(bridge=False):
    default = ', Default' if bridge else ''
    return (f'#[derive(Clone, Copy, Debug, PartialEq{default})]\npub struct Material {{\n'
            '    pub liquid: bool,\n    pub dark_theme: bool,\n' +
            ''.join(f'    pub {name}: f32,\n' for name, *_ in PARAMS) + '}\n')


def core(out):
    text = structures() + material()
    for variant in ('default', 'dark'):
        text += ('// Preserve the shared data verbatim, including angle constants.\n'
                 '#[allow(clippy::approx_constant)]\n'
                 f'pub const LIQUID_{variant.upper()}: LiquidMaterial = ' +
                 initializer(VARIANTS[variant], 'LiquidMaterial') + ';\n')
    text += 'impl Default for Material { fn default() -> Self { Self { liquid: false, dark_theme: true,\n'
    text += ''.join(f'{name}: {scalar(value)},\n' for name, value, *_ in PARAMS) + '} } }\n'
    text += 'impl Material { pub fn sanitized(mut self) -> Self {\n'
    text += ''.join(f'self.{name} = crate::sanitize_scalar(self.{name}, {scalar(value)}, {scalar(lo)}, {scalar(hi)});\n'
                    for name, value, lo, hi in PARAMS)
    text += ('self.refraction_threshold1 = self.refraction_threshold1.max(self.refraction_threshold0 + 0.01_f32);\n'
             'self\n} }\n')
    text += 'pub const DESCRIPTORS: &[crate::Descriptor] = &[\n'
    text += ''.join(f'crate::Descriptor {{ name: "{name}", default: {scalar(value)}, min: {scalar(lo)}, max: {scalar(hi)} }},\n'
                    for name, value, lo, hi in PARAMS) + '];\n'
    (out / 'material.rs').write_text('// Generated by scripts/embed-rust.py.\n' + text)


def bridge(out):
    types = structures(True) + material(True)
    template = (ROOT / 'crates/hyprliquid-bridge/src/ffi.rs.in').read_text()
    text = template.replace('// GENERATED_TYPES', types)
    # Core and bridge types are distinct: generated safe field copies are the
    # entire conversion boundary, including presence flags for optional numbers.
    for name, members in definitions():
        text += f'impl From<core::{name}> for ffi::{name} {{ fn from(v: core::{name}) -> Self {{ Self {{\n'
        for key, kind in members:
            field = snake(key)
            value = f'v.{field}'
            if kind.startswith('Liquid'):
                value += '.into()'
            elif kind == 'Option<f64>':
                value = f'ffi::OptionalNumber {{ present: v.{field}.is_some(), value: v.{field}.unwrap_or_default() }}'
            text += f'{field}: {value},\n'
        text += '} } }\n'
    fields = ['liquid', 'dark_theme'] + [name for name, *_ in PARAMS]
    for source, destination in [('core', 'ffi'), ('ffi', 'core')]:
        text += f'impl From<{source}::Material> for {destination}::Material {{ fn from(v: {source}::Material) -> Self {{ Self {{\n'
        text += ''.join(f'{name}: v.{name},\n' for name in fields) + '} } }\n'
    (out / 'ffi.rs').write_text('// Generated by scripts/embed-rust.py.\n' + text)

    cpp = '// Generated field copies; no material equations.\n#pragma once\n'
    for name, members in definitions():
        cpp += f'inline S{name} fromRust(const hyprliquid::ffi::{name}& v) noexcept {{\n    return {{'
        values = []
        for key, kind in members:
            value = 'v.' + snake(key)
            if kind.startswith('Liquid'):
                value = f'fromRust({value})'
            elif kind == 'Option<f64>':
                value = f'{value}.present ? std::optional<double>({value}.value) : std::nullopt'
            values.append(value)
        cpp += ', '.join(values) + '};\n}\n'
    (out / 'LiquidConversions.hpp').write_text(cpp)


if __name__ == '__main__':
    destination = Path(sys.argv[2])
    destination.mkdir(parents=True, exist_ok=True)
    {'core': core, 'bridge': bridge}[sys.argv[1]](destination)
